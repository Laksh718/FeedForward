"""Readable markdown summary of reports/metrics.json (generated, never typed by hand)."""

import json

TABLE_HEAD = ("| Model | MAE | RMSE | Pinball 0.1 / 0.5 / 0.9 | Coverage P10-P90 | Width |\n"
              "|---|---|---|---|---|---|\n")


def _row(d: dict) -> str:
    """Cells of one metrics row."""
    cells = [f"{d['mae']:.0f}", f"{d['rmse']:.0f}"]
    if "coverage_10_90" in d:
        cells += [f"{d['pinball_0.1']:.0f} / {d['pinball_0.5']:.0f} / {d['pinball_0.9']:.0f}",
                  f"{100 * d['coverage_10_90']:.0f}%", f"{d['width_10_90']:.0f}"]
    else:
        cells += ["-", "-", "-"]
    return " | ".join(cells)


def summary_markdown(m: dict) -> str:
    """Build the whole summary document from the metrics dictionary."""
    out = ["# Model results\n\nGenerated by `python -m feedforward.models.evaluate`. Numbers are portions per dish "
           "and slot. The history is SIMULATED on a real menu, calendar and weather, so these numbers say how well "
           "the model learns that simulation, not what it would save in a real kitchen.\n"]
    for split in ("val", "test"):
        for scope, block in m[split].items():
            rows = "".join(f"| {k} | {_row(v)} |\n" for k, v in block.items() if isinstance(v, dict))
            out.append(f"\n## {split}, {scope} ({block['rows']} rows)\n\n{TABLE_HEAD}{rows}")
    out.append("\n## Rolling origin: 4 expanding folds of 28 days, regular core dishes\n\n"
               "| Fold | Test days | last_week MAE | usual_plan MAE | gbm_quantile MAE | cvae MAE | cvae coverage |\n"
               "|---|---|---|---|---|---|---|\n")
    for f in m["rolling_origin"]:
        c = f["core_regular"]
        out.append(f"| {f['fold']} | {f['test']} | {c['last_week']['mae']:.0f} | {c['usual_plan']['mae']:.0f} | "
                   f"{c['gbm_quantile']['mae']:.0f} | {c['cvae_calibrated']['mae']:.0f} | "
                   f"{100 * c['cvae_calibrated']['coverage_10_90']:.0f}% |\n")
    out.append("\n## MAE by regime: test and all folds pooled, regular core dishes\n\n"
               "| Regime | Rows | last_week | usual_plan | gbm_quantile | cvae |\n|---|---|---|---|---|---|\n")
    for r, v in m["by_regime_core_regular"].items():
        out.append(f"| {r} | {v['rows']} | {v['last_week']:.0f} | {v['usual_plan']:.0f} | "
                   f"{v['gbm_quantile']:.0f} | {v['cvae_calibrated']:.0f} |\n")
    sim = m["decision_simulation_test"]
    out.append(f"\n## Cooking decision simulation, test period, dishes without limited stock\n\n{sim['note']}\n\n"
               "| Policy | Cooked | Leftover | Leftover % of cooked | Shortage | Shortage % of demand |\n"
               "|---|---|---|---|---|---|\n")
    for k, v in sim.items():
        if isinstance(v, dict):
            out.append(f"| {k} | {v['cooked']:.0f} | {v['leftover']:.0f} | {v['leftover_pct_of_cooked']:.1f}% | "
                       f"{v['shortage']:.0f} | {v['shortage_pct_of_demand']:.1f}% |\n")
    out.append("\n## Posterior collapse check, validation\n\n"
               "| Setting | MAE of P50 | Raw coverage | KL per latent dimension |\n|---|---|---|---|\n")
    for k, v in m["latent_ablation_val"].items():
        kl = "see training_history_dev.json" if v["kl_per_dim"] is None else ", ".join(f"{x:.4f}" for x in v["kl_per_dim"])
        out.append(f"| {k} | {v['mae_p50']:.0f} | {100 * v['raw_coverage']:.0f}% | {kl} |\n")
    out.append("\n## Attendance forecaster (MAPE)\n\n| Split | Model | Naive last week |\n|---|---|---|\n")
    out += [f"| {s} | {v['model_mape_pct']:.1f}% | {v['naive_last_week_mape_pct']:.1f}% |\n"
            for s, v in m["attendance"].items()]
    out.append(f"\n## GRU experiment (regular core dishes)\n\n```\n{json.dumps(m['gru_experiment'], indent=1, default=float)}\n```\n")
    return "".join(out)
