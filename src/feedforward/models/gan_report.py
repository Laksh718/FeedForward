"""reports/gan_report.md and one histogram per event type (reports/gan/), written with real numbers from the run."""

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.stats import ks_2samp  # noqa: E402

from feedforward import config as C  # noqa: E402
from feedforward.data.gan_data import GAN_DIR, RARE_TYPES  # noqa: E402


def describe(x: pd.Series) -> list[str]:
    """mean, std, P10, P50, P90 as text."""
    q = np.percentile(x, [10, 50, 90])
    return [f"{x.mean():,.0f}", f"{x.std():,.0f}", f"{q[0]:,.0f}", f"{q[1]:,.0f}", f"{q[2]:,.0f}"]


def write_gan_report(kept: pd.DataFrame, real: pd.DataFrame, counts: dict) -> None:
    """Real against synthetic demand per event type (portions), KS distance, histograms and the run facts."""
    out_dir = C.REPORTS_DIR / "gan"
    out_dir.mkdir(parents=True, exist_ok=True)
    summary = json.loads((GAN_DIR / "training_summary.json").read_text(encoding="utf-8"))
    lines = ["# Rare event GAN report", "",
             "Generated by `python -m feedforward.plugins.gan_extra_data --generate`. Numbers are portions per dish and slot. "
             "The history is SIMULATED, so this says how well the GAN copies that simulation. "
             "Real = train period core dish rows. Synthetic = rows kept after the checks.", "",
             f"- Epochs trained: {summary['epochs_trained']} (best checkpoint at epoch {summary['best_epoch']}, "
             f"mean KS {summary['best_mean_ks']:.3f}, seed {summary['seed']}, {summary['seconds']} s on CPU)",
             f"- Stopped early: {summary['stopped_early'] or 'no (no mode collapse seen)'}",
             f"- Training table: {summary['data']['table_rows']} rows ({summary['data']['rare_rows']} rare, "
             f"{summary['data']['normal_rows']} normal); rare rows by event: {summary['data']['rare_by_type']}",
             f"- Generated: {counts['generated']} rows ({counts['samples_per_condition']} per condition)",
             f"- Rejected: {counts['rejected_total']} ({', '.join(f'{k}: {v}' for k, v in counts['rejected'].items())})",
             f"- Kept: {counts['kept']} rows, by event: {counts['kept_by_event']}", "",
             "## Real against synthetic demand", "",
             "| Event type | Source | Rows | Mean | Std | P10 | P50 | P90 | KS statistic (p value) |", "|---|---|---|---|---|---|---|---|---|"]
    for event in RARE_TYPES:
        r = real.loc[real["event_type"] == event, "demand_qty"]
        s = kept.loc[kept["event_type"] == event, "demand_qty"]
        if len(s) == 0 or len(r) == 0:
            lines.append(f"| {event} | no synthetic rows kept | 0 | | | | | | |")
            continue
        ks = ks_2samp(r, s)
        lines.append(f"| {event} | real | {len(r)} | " + " | ".join(describe(r)) + " | |")
        lines.append(f"| {event} | synthetic | {len(s)} | " + " | ".join(describe(s)) + f" | {ks.statistic:.3f} ({ks.pvalue:.3g}) |")
        fig, ax = plt.subplots(figsize=(5, 3))
        bins = np.linspace(0, max(r.max(), s.max()), 30)
        ax.hist(r, bins=bins, alpha=0.55, density=True, label="real")
        ax.hist(s, bins=bins, alpha=0.55, density=True, label="synthetic")
        ax.set_title(f"{event}: demand per dish and slot")
        ax.set_xlabel("portions")
        ax.legend()
        fig.tight_layout()
        fig.savefig(out_dir / f"hist_{event}.png", dpi=110)
        plt.close(fig)
    lines += ["", "Histograms: `reports/gan/hist_<event>.png`. A KS statistic near 0 means the two distributions look alike; "
              "the synthetic rows also include upcoming calendar days, whose dish mix differs from the train period, "
              "so a small gap is expected."]
    (C.REPORTS_DIR / "gan_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
