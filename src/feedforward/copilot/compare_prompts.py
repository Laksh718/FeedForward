"""Runs the five use case scenarios under PROMPT_V1 and PROMPT_V2 and writes reports/prompt_comparison.md.

python -m feedforward.copilot.compare_prompts

Needs GROQ_API_KEY in .env for the two language model columns. Without it the report still lists the questions,
the figures and the template answers, and says plainly that the language model columns were not run.
"""

import re
from datetime import date, timedelta

from feedforward import config as C
from feedforward.copilot import llm
from feedforward.copilot.context_builder import build_context
from feedforward.copilot.explain import _dish_keys, ungrounded_numbers
from feedforward.copilot.nlu import understand
from feedforward.copilot.prompts import build_v1, build_v2
from feedforward.copilot.templates import template_answer
from feedforward.models.forecast_service import ForecastService, Overrides

SCENARIOS = [
    ("1. Why a dish is above or below the usual plan", "Why is Chappathi above the usual plan?"),
    ("2. What if attendance rises 15 percent", "What if attendance rises 15%?"),
    ("3. What an exam week does to demand", "What does an exam week do to demand?"),
    ("4. Summarise the week's surplus risk", "Summarise the week's surplus risk."),
    ("5. Explain the likely range to a non technical person", "Explain the P10 to P90 range to someone who is not technical."),
]
FORMAT_PARTS = ("Short answer:", "Key drivers:", "One caution:")
JARGON = re.compile(r"\bP10\b|\bP50\b|\bP90\b|quantile|latent|algorithm", re.I)
OFFERS_ACTION = re.compile(r"\bI (can|will|'ll|could) (change|update|adjust|approve|set|increase|reduce|order)", re.I)


def score(text: str, context: dict) -> dict:
    """Simple, checkable properties of an answer."""
    return {"words": len(text.split()), "figures_not_in_data": ungrounded_numbers(text, context),
            "has_three_part_format": all(p in text for p in FORMAT_PARTS), "uses_jargon": bool(JARGON.search(text)),
            "offers_to_act": bool(OFFERS_ACTION.search(text))}


def _run(messages: list[dict]) -> str:
    try:
        return llm.complete(messages)
    except llm.LLMUnavailable as exc:
        return f"(not run: {exc})"


def main() -> None:
    """Build the comparison report."""
    svc, today = ForecastService(), date.fromisoformat(C.TODAY)
    live = llm.is_configured()
    out = ["# Prompt comparison: PROMPT_V1 (plain) against PROMPT_V2 (grounded)\n",
           "Generated by `python -m feedforward.copilot.compare_prompts`.\n",
           f"Language model: {'configured, answers below are real model output' if live else 'NOT configured (no GROQ_API_KEY in .env). The language model columns were not run; nothing below is invented.'}\n",
           "V1 sends only the question. V2 sends a role, rules, two worked examples, the context JSON of exact figures and the question.\n"]
    table = ["| Scenario | V1 figures not in the data | V1 three part format | V1 jargon | V2 figures not in the data | V2 three part format | V2 jargon |",
             "|---|---|---|---|---|---|---|"]
    body = []
    for title, question in SCENARIOS:
        ctx = build_context(understand(question, _dish_keys()), svc, today + timedelta(days=1), "lunch", "core", Overrides(), today)
        template = template_answer(ctx)
        v1 = _run(build_v1(question)) if live else "(not run: no language model configured)"
        v2 = _run(build_v2(question, ctx)) if live else "(not run: no language model configured)"
        s1, s2 = (score(v1, ctx) if live else None), (score(v2, ctx) if live else None)
        cell = lambda s, k: "n/a" if s is None else str(len(s[k]) if k == "figures_not_in_data" else s[k])  # noqa: E731
        table.append(f"| {title} | {cell(s1, 'figures_not_in_data')} | {cell(s1, 'has_three_part_format')} | {cell(s1, 'uses_jargon')} | "
                     f"{cell(s2, 'figures_not_in_data')} | {cell(s2, 'has_three_part_format')} | {cell(s2, 'uses_jargon')} |")
        body.append(f"\n## {title}\n\n**Question:** {question}\n\n**Understood as:** `{ctx['intent']}`\n\n"
                    f"**V1 answer (question only)**\n\n```\n{v1}\n```\n\n**V2 answer (grounded)**\n\n```\n{v2}\n```\n\n"
                    f"**Template answer (no language model), same figures**\n\n```\n{template}\n```\n")
    out += ["\n## Summary\n\nFigures not in the data means numbers of 10 or more in the answer that do not appear in the context JSON.\n\n"] + [row + "\n" for row in table]
    (C.REPORTS_DIR / "prompt_comparison.md").write_text("".join(out + body), encoding="utf-8")
    print("wrote reports/prompt_comparison.md", "(language model run)" if live else "(language model NOT run: no key)")


if __name__ == "__main__":
    main()
