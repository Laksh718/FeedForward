"""Bundle the preprocessing, cleaning and feature extraction code into one readable document."""

from feedforward import config as C

STAGES = {
    "1. Preprocessing (loading, validation, NLP text pipeline)": [
        "config.py", "data/schemas.py", "data/loaders.py", "data/nlp_text.py", "data/nlp_entities.py",
        "data/preprocess.py", "data/nlp_report.py"],
    "2. Cleaning (raw kitchen file to clean table)": ["data/cleaning.py"],
    "3. Feature extraction and time series datasets": [
        "data/text_features.py", "data/calendar_future.py", "data/feature_registry.py", "data/features.py",
        "data/inventory_features.py", "data/splits.py", "data/timeseries.py"],
}
OUT = C.ARTIFACTS_DIR / "code_bundle_preprocessing.md"


def main() -> None:
    """Write artifacts/code_bundle_preprocessing.md (regenerate whenever the code changes)."""
    src = C.PROJECT_ROOT / "src" / "feedforward"
    parts = ["# Preprocessing, cleaning and feature extraction code\n",
             "Generated by `python -m feedforward.export_code`. The source of truth is `src/feedforward/`.\n"]
    for stage, files in STAGES.items():
        parts.append(f"\n## {stage}\n")
        for name in files:
            code = (src / name).read_text(encoding="utf-8")
            parts.append(f"\n### `src/feedforward/{name}`\n\n```python\n{code.rstrip()}\n```\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(C.PROJECT_ROOT)} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
